#!/usr/bin/env python3
"""Generate ENOSYS stubs for POSIX functions that KOReader's FFI declarations mention (ffi-cdecl/posix_h_other_mipsel.lua)
but that the PSP's libc does not provide, so that `ffi.C.name` resolves and fails gracefully instead of raising a
"symbol not found" error. Usage: gen-psp-posix-stubs.py OUT.c --nm PSP-NM --cdecl FILE --have LIB... [--success NAME...]
"""
import argparse, re, subprocess

ap = argparse.ArgumentParser()
ap.add_argument("out"); ap.add_argument("--nm", default="psp-nm"); ap.add_argument("--cdecl", required=True)
ap.add_argument("--have", nargs="*", default=[]); ap.add_argument("--success", nargs="*", default=[])
a = ap.parse_args()

have = set()
for lib in a.have:
    for line in subprocess.run([a.nm, "-g", "--defined-only", lib], capture_output=True, text=True).stdout.splitlines():
        p = line.split()
        if len(p) == 3: have.add(p[2])

decls = {}
for line in open(a.cdecl):
    m = re.match(r'^((?:const |unsigned |struct |signed )*[A-Za-z_]\w*[ \t\*]+\**)(\w+)\((.*)\);\s*$', line)
    if m and not line.startswith(("typedef", "static", "//")):
        decls[m.group(2)] = m.group(1)
with open(a.out, "w") as f:
    f.write("/* Generated by utils/gen-psp-posix-stubs.py. Do not edit. */\n#include <errno.h>\n#include <stddef.h>\n")
    n = 0
    for name, ret in sorted(decls.items()):
        if name in have or name.startswith('_'): continue  # (`_exit` etc. come from the startup code)
        n += 1
        if name in a.success:
            f.write(f"long {name}() {{ return 0; }}\n")
        elif "*" in ret:
            f.write(f"void *{name}() {{ errno = ENOSYS; return NULL; }}\n")
        elif ret.strip() == "void":
            f.write(f"void {name}() {{ errno = ENOSYS; }}\n")
        else:
            f.write(f"long {name}() {{ errno = ENOSYS; return -1; }}\n")
print(f"{n} stubs", __import__("sys").stderr)
