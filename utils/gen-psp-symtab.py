#!/usr/bin/env python3
"""Generate the static symbol table used by LuaJIT's `ffi.C` / `ffi.load` on the PSP (no dynamic loader there).

Usage: gen-psp-symtab.py OUT.c --nm PSP-NM --lua-dir DIR... -- INPUT.a|.o|.obj ...

A symbol is exported if it is a global definition in one of the INPUT files AND its name appears as an identifier in
one of the Lua files (that is where `ffi.cdef` declarations / `ffi.C.xxx` uses live). `luaopen_*` entry points found in
the inputs are emitted in a second table, to back `package.loadlib` / `package.preload`.
"""
import argparse, os, re, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--nm", default="psp-nm")
ap.add_argument("--lua-dir", action="append", default=[])
ap.add_argument("--extra", action="append", default=[], help="symbols to always export")
ap.add_argument("inputs", nargs="+")
a = ap.parse_args()

idents = set(a.extra)
rx = re.compile(rb"[A-Za-z_][A-Za-z0-9_]*")
for d in a.lua_dir:
    for root, _, files in os.walk(d):
        for f in files:
            if f.endswith(".lua"):
                with open(os.path.join(root, f), "rb") as fh:
                    idents.update(m.decode() for m in rx.findall(fh.read()))

defined = {}   # name -> kind ('f' or 'd')
for inp in a.inputs:
    out = subprocess.run([a.nm, "-g", "--defined-only", inp], capture_output=True, text=True, check=False).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TDBRVWSGtdbr":
            name = parts[2]
            if name.startswith("_Z") or name.startswith("."):
                continue
            defined.setdefault(name, parts[1])

exported = sorted(n for n in defined if n in idents and not n.startswith("luaopen_"))
luaopen = sorted(n for n in defined if n.startswith("luaopen_"))

with open(a.out, "w") as f:
    f.write("/* Generated by utils/gen-psp-symtab.py. Do not edit. */\n#include <stddef.h>\n")
    f.write("struct lj_static_sym { const char *name; void *addr; };\n")
    for n in exported:
        f.write(f"extern char {n}[];\n")
    f.write("const struct lj_static_sym lj_static_symtab[] = {\n")
    for n in exported:                       # sorted() on str == strcmp order for ASCII
        f.write(f'    {{ "{n}", (void *){n} }},\n')
    f.write("    { NULL, NULL }\n};\n\n")
    for n in luaopen:
        f.write(f"extern int {n}(void *L);\n")
    f.write("struct psp_luaopen { const char *name; int (*fn)(void *); };\n")
    f.write("const struct psp_luaopen psp_luaopen_table[] = {\n")
    for n in luaopen:
        f.write(f'    {{ "{n}", {n} }},\n')
    f.write("    { NULL, NULL }\n};\n")
print(f"{len(exported)} ffi symbols, {len(luaopen)} luaopen entry points", file=sys.stderr)
