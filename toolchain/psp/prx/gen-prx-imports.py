#!/usr/bin/env python3
"""Generate the import stubs of a KOReader PSP module (see ko_prx.h).

Usage: gen-prx-imports.py OUT.S NAME...   (or @FILE with one name per line)

Each imported function gets a tiny trampoline in its own section (so --gc-sections drops unused ones) that jumps
through a slot; `ko_imports` lists the (name, slot) pairs the module glue fills at start.
"""
import sys
out = sys.argv[1]
names = []
for a in sys.argv[2:]:
    if a.startswith("@"):
        names += [l.strip() for l in open(a[1:]) if l.strip()]
    else:
        names.append(a)
names = sorted(set(names))
with open(out, "w") as f:
    f.write("/* Generated by gen-prx-imports.py. Do not edit. */\n\t.set noreorder\n\t.set noat\n")
    for n in names:
        f.write(f'''
\t.section .text.koimp.{n},"ax",@progbits
\t.globl {n}
\t.type {n},@function
\t.ent {n}
{n}:
\tlui $25,%hi(ko_slot_{n})
\tlw $25,%lo(ko_slot_{n})($25)
\tjr $25
\tnop
\t.end {n}
\t.size {n},.-{n}
\t.section .data.koslot.{n},"aw",@progbits
\t.align 2
ko_slot_{n}:
\t.word 0
''')
    f.write('\n\t.section .rodata.koimpnames,"a",@progbits\n')
    for n in names:
        f.write(f'ko_name_{n}:\t.asciz "{n}"\n')
    f.write('\n\t.section .rodata.koimports,"a",@progbits\n\t.align 2\n\t.globl ko_imports\nko_imports:\n')
    for n in names:
        f.write(f"\t.word ko_name_{n}, ko_slot_{n}\n")
    f.write("\t.word 0, 0\n")
print(f"{len(names)} imports", file=sys.stderr)
