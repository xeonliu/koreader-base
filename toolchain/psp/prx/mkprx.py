#!/usr/bin/env python3
"""Link a KOReader PSP module (PRX). See ko_prx.h for the design.

  mkprx.py --name cre --out DIR [--cxx] [--lua-dir DIR]... [--export SYM]... [--ldflag X]... -- OBJ|LIB...

Steps: (1) find the symbols the objects need from outside, (2) generate import stubs for them and an export table
(symbols named in the Lua sources given with --lua-dir, plus luaopen_* and --export), (3) link with --gc-sections,
(4) drop the stubs nothing uses and relink, (5) psp-fixup-imports + psp-prxgen.
Writes DIR/NAME.prx and DIR/NAME.imports (what the main program must provide).
"""
import argparse, os, re, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument("--name", required=True); ap.add_argument("--out", required=True)
ap.add_argument("--cxx", action="store_true"); ap.add_argument("--lua-dir", action="append", default=[])
ap.add_argument("--export", action="append", default=[]); ap.add_argument("--ldflag", action="append", default=[])
ap.add_argument("--cflags", default="-O2 -G0 -mno-abicalls -fno-pic")
ap.add_argument("--static-lib", action="append", default=[], help="library linked statically into the module (after the imports)")
ap.add_argument("inputs", nargs="+")
a = ap.parse_args()

here = os.path.dirname(os.path.abspath(__file__))
sdk = subprocess.run(["psp-config", "--pspsdk-path"], capture_output=True, text=True).stdout.strip()
work = os.path.join(a.out, a.name + ".build"); os.makedirs(work, exist_ok=True)
cc = "psp-g++" if a.cxx else "psp-gcc"
def run(cmd, check=True):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.stderr.write(" ".join(cmd) + "\n" + r.stdout[-3000:] + r.stderr[-6000:]); sys.exit(1)
    return r

# Glue + export table.
glue = os.path.join(work, "glue.o")
run(["psp-gcc"] + a.cflags.split() + [f'-DKO_MODULE_NAME="{a.name}"', "-I" + here, "-I" + sdk + "/include", "-c", os.path.join(here, "ko_prx_glue.c"), "-o", glue])
idents = set(a.export)
rx = re.compile(rb"[A-Za-z_][A-Za-z0-9_]*")
for d in a.lua_dir:
    for root, _, files in os.walk(d):
        for f in files:
            if f.endswith(".lua"):
                idents.update(m.decode() for m in rx.findall(open(os.path.join(root, f), "rb").read()))
defined = set()
for inp in a.inputs:
    for line in run(["psp-nm", "-g", "--defined-only", inp], check=False).stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in "TDBRVWSG" and not p[2].startswith("_Z"): defined.add(p[2])
exports = sorted(n for n in defined if n in idents or n.startswith("luaopen_"))
exp_c = os.path.join(work, "exports.c")
with open(exp_c, "w") as f:
    f.write('/* Generated by mkprx.py. */\n#include "ko_prx.h"\n')
    for n in exports: f.write(f"extern char {n}[];\n")
    f.write("const struct ko_sym ko_exports[] = {\n" + "".join(f'    {{ "{n}", (void *){n} }},\n' for n in exports) + "    { 0, 0 }\n};\n")
    f.write(f"const int ko_nexports = {len(exports)};\n")
exp_o = os.path.join(work, "exports.o")
run(["psp-gcc"] + a.cflags.split() + ["-I" + here, "-c", exp_c, "-o", exp_o])

start_o = os.path.join(work, "start.o"); end_o = os.path.join(work, "end.o")
run(["psp-gcc", "-c", os.path.join(here, "ko_prx_start.S"), "-o", start_o])
run(["psp-gcc", "-c", os.path.join(here, "ko_prx_end.S"), "-o", end_o])
elf = os.path.join(work, a.name + ".elf")
def link(imports_obj, extra=()):
    cmd = [cc, "-nostdlib", "-Wl,-q,-T" + sdk + "/lib/linkfile.prx", "-Wl,--gc-sections", "-Wl,--defsym=ko_eh_frame_start=ADDR(.eh_frame)", "-Wl,-zmax-page-size=128",
           "-o", elf, start_o, glue, exp_o] + list(a.inputs) + ([imports_obj] if imports_obj else []) + [sdk + "/lib/prxexports.o"] \
          + list(a.ldflag) + list(extra) + a.static_lib + ["-L" + sdk + "/lib", "-lpspmodinfo", "-lgcc", end_o]
    return run(cmd, check=False)

def gen_imports(names):
    s = os.path.join(work, "imports.S"); o = os.path.join(work, "imports.o")
    lst = os.path.join(work, "imports.lst"); open(lst, "w").write("\n".join(sorted(names)) + "\n")
    run([sys.executable, os.path.join(here, "gen-prx-imports.py"), s, "@" + lst])
    run(["psp-gcc", "-c", s, "-o", o])
    return o

# 1. What is undefined?
r = link(gen_imports([]), ["-Wl,--warn-unresolved-symbols"])
undef = set(re.findall(r"undefined reference to `([^']+)'", r.stderr))
undef.discard("_impure_ptr")
# Imports are call trampolines, so they only work for functions: refuse data symbols of the C library.
libdir = os.path.join(os.path.dirname(sdk), "lib")
data = set()
for lib in ("libc.a", "libm.a", "libpthread.a"):
    for line in run(["psp-nm", "-g", "--defined-only", os.path.join(libdir, lib)], check=False).stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in "DBRSGCV": data.add(p[2])
bad = sorted(undef & data)
if bad:
    sys.stderr.write(f"{a.name}: data symbols cannot be imported from the main program: {' '.join(bad)}\n"); sys.exit(1)
# 2. Link with stubs for all of it.
r = link(gen_imports(undef))
if r.returncode != 0:
    sys.stderr.write(r.stderr[-6000:]); sys.exit(1)
# 3. Keep only the stubs that survived --gc-sections, relink.
alive = set()
for line in run(["psp-nm", elf]).stdout.splitlines():
    p = line.split()
    if len(p) == 3 and p[2] in undef and p[1] in "Tt": alive.add(p[2])
r = link(gen_imports(alive))
if r.returncode != 0:
    sys.stderr.write(r.stderr[-6000:]); sys.exit(1)
r = run(["psp-fixup-imports", elf], check=False)   # nothing to fix when the module imports no firmware functions
if r.returncode != 0 and "no .lib.stub" not in r.stdout + r.stderr:
    sys.stderr.write(r.stdout + r.stderr); sys.exit(1)
prx = os.path.join(a.out, a.name + ".prx")
run(["psp-prxgen", elf, prx])
open(os.path.join(a.out, a.name + ".imports"), "w").write("\n".join(sorted(alive)) + "\n")
print(f"{a.name}.prx: {os.path.getsize(prx)} bytes, {len(exports)} exports, {len(alive)} imports ({len(undef) - len(alive)} unused dropped)")
